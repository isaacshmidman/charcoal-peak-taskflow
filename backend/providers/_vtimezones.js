/**
 * Return the VTIMEZONE block for `tzid` as an array of plain (unfolded) ICS
 * lines, or null if we don't have a definition for it. The caller is
 * responsible for folding + CRLF-joining as part of the surrounding VCALENDAR.
 *
 * @param {string} tzid
 * @returns {string[] | null}
 */
export function buildVTimezone(tzid) {
  if (!tzid) return null;
  const block = ZONES[tzid];
  if (!block) return null;
  return block.split(/\r?\n/).filter(Boolean);
}

/**
 * Best-effort canonicalization for legacy or short tz names — keep the
 * IANA primary if possible. Today this is a passthrough; lives here so
 * callers don't have to change when we add aliasing.
 *
 * @param {string} tzid
 */
export function canonicalizeTzid(tzid) {
  return String(tzid || "").trim();
}
