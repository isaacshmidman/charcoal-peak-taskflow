/**
 * Hardcoded VTIMEZONE blocks for the most-used IANA zones.
 *
 * Why hardcode rather than generate from a tz database:
 *   - Node's bundled ICU has the offset rules but no convenient API for
 *     emitting RFC 5545 VTIMEZONE bodies.
 *   - The full IANA zone list runs to ~600 zones, the vast majority of
 *     which Zephyrly users will never touch.
 *   - Apple's CalDAV implementation is tolerant of missing VTIMEZONE blocks
 *     for primary IANA names (it interprets TZID against its own DB), but
 *     other CalDAV servers — including Outlook/Exchange — strictly require
 *     a VTIMEZONE definition for every TZID referenced in a VEVENT.
 *
 * Adding a new zone:
 *   1. Get the canonical RFC 5545 block from the IANA tz database
 *      (https://www.tzurl.org/zones/) or another VEVENT exporter.
 *   2. Drop it in below, keyed by the IANA name (case-sensitive).
 *   3. Lines must be CRLF-terminated when assembled (we add the CRLF in
 *      buildVTimezone) — store them as plain LF here for readability.
 *
 * Architecture note:
 *   This module exposes a single function `buildVTimezone(tzid)` so the
 *   call sites don't depend on the storage shape. If we later swap the
 *   hardcoded table for a runtime tz library (luxon, @date-fns/tz, etc.),
 *   only this file changes.
 */

